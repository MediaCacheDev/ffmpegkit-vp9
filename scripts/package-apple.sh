#!/bin/bash
#
# package-apple.sh
# Zips each XCFramework in dist/ios/Frameworks into dist/release/ for Swift Package Manager
# (one binaryTarget per framework), and regenerates Package.swift and ffmpegkit-vp9.podspec
# with the checksums of this version's release assets. Commit both before tagging the version:
# SPM and CocoaPods read them from the tag.
#
# Called by package-release.sh, which first creates the combined iOS zip the podspec downloads.
#

set -euo pipefail

source "$(dirname "${BASH_SOURCE[0]}")/common.sh"

VERSION="$FFMPEGKIT_VP9_VERSION"
FRAMEWORKS="$DIST_DIR/ios/Frameworks"
OUT="$DIST_DIR/release"
COMBINED_ZIP="$OUT/ffmpegkit-vp9-$VERSION-ios-xcframeworks.zip"
RELEASE_URL="https://github.com/MediaCacheDev/ffmpegkit-vp9/releases/download/$VERSION"

# ffmpegkit first: it's the module apps import; the rest are the FFmpeg libraries it links.
NAMES=(ffmpegkit libavcodec libavdevice libavfilter libavformat libavutil libswresample libswscale)

if [ ! -f "$COMBINED_ZIP" ]; then
    echo "❌ Missing $COMBINED_ZIP; run package-release.sh"
    exit 1
fi

TARGETS=""
for name in "${NAMES[@]}"; do
    zip_name="ffmpegkit-vp9-$VERSION-$name.xcframework.zip"
    rm -f "$OUT/$zip_name"
    (cd "$FRAMEWORKS" && zip -qry "$OUT/$zip_name" "$name.xcframework")
    checksum="$(shasum -a 256 "$OUT/$zip_name" | cut -d' ' -f1)"
    TARGETS+="        .binaryTarget(
            name: \"$name\",
            url: \"\(releaseURL)/$zip_name\",
            checksum: \"$checksum\"
        ),
"
    echo "  ✔ $zip_name"
done

PRODUCT_TARGETS="$(printf '"%s", ' "${NAMES[@]}")"
PRODUCT_TARGETS="${PRODUCT_TARGETS%, }"

cat > "$ROOT_DIR/Package.swift" <<EOF
// swift-tools-version:5.9
// Generated by scripts/package-apple.sh for ffmpegkit-vp9 $VERSION.

import PackageDescription

let releaseURL = "$RELEASE_URL"

let package = Package(
    name: "ffmpegkit-vp9",
    platforms: [.iOS(.v12)],
    products: [
        .library(name: "ffmpegkit-vp9", targets: [$PRODUCT_TARGETS]),
    ],
    targets: [
${TARGETS%,
}
    ]
)
EOF
echo "  ✔ Package.swift"

cat > "$ROOT_DIR/ffmpegkit-vp9.podspec" <<EOF
# Generated by scripts/package-apple.sh for ffmpegkit-vp9 $VERSION.
# Not on CocoaPods trunk; use it with
#   pod 'ffmpegkit-vp9', :podspec => 'https://raw.githubusercontent.com/MediaCacheDev/ffmpegkit-vp9/$VERSION/ffmpegkit-vp9.podspec'

Pod::Spec.new do |s|
  s.name         = 'ffmpegkit-vp9'
  s.version      = '$VERSION'
  s.summary      = 'FFmpegKit 6.0 with a minimal FFmpeg that decodes VP9 WebM with alpha through libvpx.'
  s.homepage     = 'https://github.com/MediaCacheDev/ffmpegkit-vp9'
  s.license      = { :type => 'LGPL-3.0-or-later', :file => 'Frameworks/ffmpegkit.xcframework/ios-arm64/ffmpegkit.framework/LICENSE' }
  s.author       = { 'Daniel Kasprowicz' => '9932671+danielkpl2@users.noreply.github.com' }
  s.platform     = :ios, '12.1'
  s.source       = { :http => '$RELEASE_URL/$(basename "$COMBINED_ZIP")',
                     :sha256 => '$(shasum -a 256 "$COMBINED_ZIP" | cut -d' ' -f1)' }
  s.vendored_frameworks = 'Frameworks/*.xcframework'
end
EOF
echo "  ✔ ffmpegkit-vp9.podspec"
